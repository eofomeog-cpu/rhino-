ADVANCE = 5.6


def text_lines(s, height, x=0.0, y=0.0, align="left"):
    """Return LineStrings for `s` with cap height `height`, baseline at (x, y)."""
    k = height / 6.0
    width = (len(s) * ADVANCE - (ADVANCE - 4)) * k
    if align == "center":
        x -= width / 2
    elif align == "right":
        x -= width
    out = []
    for i, ch in enumerate(s.upper() if s not in ("x",) else s):
        g = G.get(ch, G.get(ch.upper(), G["#"]))
        ox = x + i * ADVANCE * k
        for stroke in g:
            out.append(LineString([(ox + a * k, y + b * k) for a, b in stroke]))
    return out


def text_size(s, height):
    k = height / 6.0
    return (len(s) * ADVANCE - (ADVANCE - 4)) * k, height


def transform(lines, angle=0.0, origin=(0, 0), mirror_x=False, dx=0.0, dy=0.0):
    res = []
    for l in lines:
        g = l
        if mirror_x:
            g = affinity.scale(g, -1, 1, origin=origin)
        if angle:
            g = affinity.rotate(g, angle, origin=origin)
        res.append(affinity.translate(g, dx, dy))
    return res
